"""Isolated, deterministic local HTML frames -> FFmpeg. No Google session is opened."""
import argparse
import hashlib
import json
import math
import subprocess
import struct
import time
import wave
from pathlib import Path
from playwright.sync_api import sync_playwright


def sound_effects(path, duration, cues):
    """Original, quiet transient foley; no downloaded music or replacement speech."""
    rate=48000;samples=[0.0]*math.ceil(duration*rate)
    for index,at in enumerate(cues):
        length=.17 if index%2==0 else .23
        start=round(at*rate)
        for i in range(round(length*rate)):
            t=i/rate;envelope=math.sin(math.pi*t/length)**2*math.exp(-t*17)
            frequency=620+index*105
            tone=math.sin(2*math.pi*(frequency*t-750*t*t))
            if start+i<len(samples):samples[start+i]+=.038*envelope*tone
    with wave.open(str(path),'wb') as output:
        output.setnchannels(1);output.setsampwidth(2);output.setframerate(rate)
        output.writeframes(struct.pack('<'+'h'*len(samples),*(round(max(-1,min(1,s))*32767) for s in samples)))


def capture(project, audio, subtitles, duration, target, raw=None, native_captions=False):
    fps=24
    frames=math.ceil(duration*fps)
    folder=project.parent
    command=['ffmpeg','-v','error','-y','-threads','1','-filter_complex_threads','1',
        '-f','image2pipe','-framerate',str(fps),'-vcodec','png','-i','pipe:0']
    if raw:
        command+=['-threads','1','-i',str(raw)]
        filters='[1:v]scale=720:1280:force_original_aspect_ratio=increase,crop=720:1280,setsar=1,fps=24[bg];[bg][0:v]overlay=shortest=1:format=auto[composite];[composite]'
        audio_index='2:a:0'
    else:
        filters='[0:v]'
        audio_index='1:a:0'
    command+=['-i',str(audio)]
    filters+='format=yuv420p'+('' if native_captions else f',subtitles={subtitles}')+'[v]'
    # All cues are generated by the same local deterministic composition clock.
    sfx=folder/'motion_sfx.wav'
    if native_captions:
        command+=['-i',str(sfx)]
        sfx_index='3:a:0' if raw else '2:a:0'
        filters+=f';[{audio_index}][{sfx_index}]amix=inputs=2:duration=first:normalize=0[a]'
        audio_index='[a]'
    command+=['-filter_complex',filters,'-map','[v]','-map',audio_index,
        '-c:v','libx264','-threads','1','-preset','veryfast','-crf','19',
        '-pix_fmt','yuv420p','-c:a','aac','-ar','48000','-ac','2','-b:a','160k',
        '-t',f'{duration:.6f}','-movflags','+faststart',str(target)]
    started=time.monotonic(); hashes=[]; layout=[]
    with (folder/'ffmpeg.log').open('w') as errors, sync_playwright() as p:
        print('motion: starting isolated browser',flush=True)
        browser=p.chromium.launch(headless=True,args=['--no-sandbox','--disable-dev-shm-usage','--renderer-process-limit=1'])
        encoder=None
        try:
            page=browser.new_page(viewport={'width':720,'height':1280},device_scale_factor=1)
            page.set_default_timeout(30000)
            # Compositions use only local assets. Never load a remote font/script at render time.
            page.route('http://**/*',lambda route:route.abort())
            page.route('https://**/*',lambda route:route.abort())
            page.goto(project.resolve().as_uri(),wait_until='domcontentloaded',timeout=45000)
            print('motion: composition loaded',flush=True)
            page.wait_for_function("document.fonts.status === 'loaded'",timeout=15000)
            print('motion: fonts ready',flush=True)
            page.evaluate('(t)=>window.seek(t)',duration)
            print('motion: timeline seeks',flush=True)
            page.evaluate('window.fitText()')
            layout=page.evaluate('window.layoutProblems()')
            if layout:raise RuntimeError('Motion text exceeds safe frame: '+repr(layout))
            caption_timing=page.evaluate('window.__captionTiming || null')
            audio_cues=page.evaluate('window.__audioCues || []')
            if native_captions:sound_effects(sfx,duration,audio_cues)
            print('motion: layout checked; encoding '+str(frames)+' frames',flush=True)
            encoder=subprocess.Popen(command,stdin=subprocess.PIPE,stderr=errors)
            selected={0,frames//4,frames//2,3*frames//4,frames-1}
            for frame in range(frames):
                page.evaluate('(t)=>window.seek(t)',frame/fps)
                png=page.screenshot(type='png',omit_background=True)
                if frame in selected:
                    hashes.append(hashlib.sha256(png).hexdigest())
                    (folder/f'frame_{frame:04d}.png').write_bytes(png)
                encoder.stdin.write(png)
            encoder.stdin.close()
            if encoder.wait(timeout=90):raise RuntimeError('FFmpeg failed; see '+str(folder/'ffmpeg.log'))
            if len(set(hashes))<2:raise RuntimeError('Motion produced identical check frames')
        finally:
            if encoder is not None and encoder.poll() is None:
                encoder.kill();encoder.wait()
            browser.close()
    result={'frames':frames,'fps':fps,'duration':duration,'wall_seconds':round(time.monotonic()-started,2),
        'sample_sha256':hashes,'layout_problems':layout,'raw_video':str(raw) if raw else None,
        'caption_timing':caption_timing,'audio_cues':audio_cues,
        'sound_design':'original_quiet_transients' if native_captions else None}
    (folder/'render.json').write_text(json.dumps(result,indent=2))
    return result


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    for name in ('project','audio','subtitles'):parser.add_argument(name,type=Path)
    parser.add_argument('duration',type=float);parser.add_argument('target',type=Path)
    parser.add_argument('--raw',type=Path)
    parser.add_argument('--native-captions',action='store_true')
    args=parser.parse_args()
    print(json.dumps(capture(args.project,args.audio,args.subtitles,args.duration,args.target,args.raw,args.native_captions)))
